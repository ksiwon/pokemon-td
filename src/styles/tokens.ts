/**
 * 글자 크기 — **12px이 하한, 그 위로는 4px 격자**.
 *
 * 예전에는 12 / 24 / 36 세 칸뿐이라 제목과 본문 사이에 아무것도 없었다. 그래서
 * 화면의 92%가 12px 한 크기로 눌렸고(sm 588회 : base 40회 : lg 13회), 그 틈을
 * 토큰 밖 리터럴(14·18·20·22px)이 몰래 메우고 있었다. 위계가 없으면 화면이 평평해
 * 보인다 — 도트 UI라서가 아니라 스케일이 없어서 생기는 문제다.
 *
 * 12px 하한은 Galmuri11이 그 아래에서 뭉개지기 때문이고, 4px 격자는 간격 토큰(SP)과
 * 같은 격자를 쓰기 위한 것이다. 여기 없는 크기를 파일에 직접 쓰지 않는다.
 */
